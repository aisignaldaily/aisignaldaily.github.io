#!/usr/bin/env python3
"""Build short per-slot slices of tools/STYLE.md so each scheduled run reads only what it needs.

STYLE.md stays the ONLY file to edit. After ANY edit to STYLE.md run:
    python3 tools/build_slots.py
and commit tools/slots/*.md together with STYLE.md.
Each slice = the file preamble + every "## " section whose title starts with one of the listed prefixes.
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent
STYLE = ROOT / "STYLE.md"
OUT = ROOT / "slots"

CORE = [
    "Working with Raheel", "FOLLOW TRIGGER", "FOLLOW-GATE", "\"Real, not AI\"", "Real people",
    "Captions", "Hook formulas", "PRE-FLIGHT REVIEW", "VIRAL PLAYBOOK", "Research notes",
    "WEEKLY SIGNATURE CALENDAR", "Weekly report rules", "Planned queue", "Links-page entries",
]
SLOTS = {
    "morning": ["\"Free swaps\"", "\"The List\"", "\"Idea gallery\"", "Trend radar", "Pick stories",
                "Carousel cover", "Slides 2-6", "\"Wait, AI can do THAT?\"", "AFFILIATE RULES",
                "Swipe mechanics", "Company posts", "NEWS-LIGHT DAYS"],
    "midday": ["\"AI you can use\"", "\"We asked AI\"", "\"Built with AI\"", "Voice rules v2",
               "Voiceover test", "\"Viral AI claim", "\"Price Drop\"", "NEWS-LIGHT DAYS", "Reels (evening)",
               "AFFILIATE RULES", "Pick stories", "Hook lab"],
    "practical": ["\"AI you can use\"", "\"Build it\"", "Blueprint company posts", "Industry blueprint series",
                  "Company posts", "Trend radar", "Hook lab", "Prompt-chain", "\"Wait, AI can do THAT?\"",
                  "\"AI team\"", "\"Idea gallery\"", "Carousel cover", "Slides 2-6", "AFFILIATE RULES",
                  "Swipe mechanics"],
    "evening": ["\"Builder lessons\"", "Reels (evening)", "Voice rules v2", "Voiceover test", "Clip test",
                "Competitor study", "\"Price Drop\"", "\"Viral AI claim", "NEWS-LIGHT DAYS", "Pick stories",
                "AFFILIATE RULES", "Breaking news"],
    "stories": ["\"Builder lessons\""],
    "breaking": ["Breaking news", "Pick stories", "Reels (evening)", "NEWS-LIGHT DAYS", "Carousel cover"],
    "friday": ["Industry blueprint series", "Voice rules v2", "Prompt-chain", "Reels (evening)",
               "AFFILIATE RULES", "Blueprint company posts", "Company posts"],
}
# Stories only needs a tiny core; breaking needs the content rules.
CORE_BY_SLOT = {
    "stories": ["Working with Raheel", "FOLLOW-GATE", "Links-page entries", "\"Real, not AI\"", "Real people"],
}

def split(text):
    parts = re.split(r"(?m)^(?=## )", text)
    pre = parts[0]
    secs = [(p.split("\n", 1)[0][3:].strip(), p) for p in parts[1:]]
    return pre, secs

def build():
    text = STYLE.read_text()
    pre, secs = split(text)
    OUT.mkdir(exist_ok=True)
    problems = []
    all_prefixes = set(CORE) | {p for v in SLOTS.values() for p in v}
    for pfx in all_prefixes:
        if not any(t.startswith(pfx) for t, _ in secs):
            problems.append(f"no section starts with {pfx!r}")
    for slot, extra in SLOTS.items():
        wanted = CORE_BY_SLOT.get(slot, CORE) + extra
        chosen = [(t, b) for t, b in secs if any(t.startswith(w) for w in wanted)]
        head = (f"<!-- GENERATED by tools/build_slots.py from tools/STYLE.md. Do NOT edit this file: edit STYLE.md, "
                f"then run `python3 tools/build_slots.py`. Slice for slot: {slot}. "
                f"If a rule you need is not here, read the matching section in tools/STYLE.md. -->\n")
        body = head + pre + "".join(b for _, b in chosen)
        (OUT / f"{slot}.md").write_text(body)
        print(f"{slot:10s} {len(chosen):2d} sections {len(body):6d} bytes (full STYLE.md: {len(text)} bytes)")
    if problems:
        print("WARNING:", *problems, sep="\n  ")
        sys.exit(1)

if __name__ == "__main__":
    build()
